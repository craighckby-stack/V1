/**
 * LESSONS-AS-MARKDOWN — the human-auditable, DB-independent mirror.
 * (concepts: upskill learnings.md, agent-lore's walkable memory web with
 * a 30 KiB budget, git-as-memory's versioned provenance, Echoless's
 * evidence classification — D6)
 *
 * Lessons live in SQLite. If the DB corrupts, every lesson dies; if the
 * operator wants to read what the system has learned, they query SQLite.
 * This module mirrors the lesson table into memory/lessons.md after
 * every distillation pass:
 *
 *   - versioned (a small diff every distillation = easy audit in git)
 *   - human-readable AND human-EDITABLE: the next distillation sees
 *     your edit in its existing-lessons context and won't re-derive a
 *     contradicting rule (the distiller prompt includes the file's
 *     lesson list, whatever its wording — your phrasing becomes the
 *     lesson's phrasing when it matches closely enough to be deduped
 *     against, which is the point)
 *   - DB-independent: institutional memory survives a DB wipe
 *   - importable: a sibling project can read the rules directly
 *
 * The write is best-effort and ONLY happens when the rendered content
 * differs from disk (no churn). The git add+commit is best-effort too —
 * index.lock contention with the loop's own commits is expected
 * occasionally; the next distillation retries, and an uncommitted
 * lessons.md just rides along in the loop's next push (pushCurrentState
 * commits the live state).
 *
 * This file is in PROTECTED_FILES: it writes content that gets COMMITTED
 * AND PUSHED — the loop must not be able to shape what it writes here.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "fs";
import { spawnSync } from "child_process";
import { db } from "@/lib/db";

import { PROJECT_ROOT } from "../core/paths";
export const LESSONS_MD_PATH = `${PROJECT_ROOT}/memory/lessons.md`;

type LessonDelegate = typeof db.lesson | undefined;

function lessons(): LessonDelegate {
  const d = (db as unknown as { lesson?: LessonDelegate }).lesson;
  return typeof d?.findMany === "function" ? d : undefined;
}

/** Render one lesson entry. Mirrors the D6 format contract:
 *
 *   ## [kind | status] first-eight-words · score 0.78 · helped 14 · hindered 4 · lapse 2 · distilled 2026-11-02
 *   **Rule:** <content>
 *   **Source:** distilled from N postmortems / hand-planted seed
 *   **Evidence:** HISTORICAL_FACT — <what the counts prove>.
 *   AI_INTERPRETATION — the rule wording itself (a judgment, not a fact).
 */
function renderEntry(row: {
  content: string;
  kind: string;
  active: boolean;
  revokedAt: Date | null;
  score: number;
  helped: number;
  hindered: number;
  lapseCount: number;
  sourceCount: number;
  sourceType: string;
  createdAt: Date;
}): string {
  const status = !row.active
    ? row.revokedAt
      ? "revoked"
      : row.kind === "advisory"
        ? "advisory"
        : "pruned"
    : "active";
  const slug = row.content
    .toLowerCase()
    .split(/\s+/)
    .slice(0, 8)
    .join("-")
    .replace(/[^a-z0-9-]/g, "")
    .slice(0, 60);
  const date = row.createdAt instanceof Date ? row.createdAt.toISOString().slice(0, 10) : String(row.createdAt).slice(0, 10);
  const header = `## [${row.kind} | ${status}] ${slug} · score ${row.score.toFixed(2)} · helped ${row.helped} · hindered ${row.hindered} · lapse ${row.lapseCount} · distilled ${date}`;
  const source =
    row.sourceType === "seed"
      ? "hand-planted seed from the system's own proven history"
      : `distilled from ${row.sourceCount} postmortem(s)`;
  const evidenceFact = `HISTORICAL_FACT — helped/hindered/lapse counts above are measured outcomes of injected prompts, not estimates.`;
  const evidenceInterp = `AI_INTERPRETATION — the rule wording is the distiller's judgment, not a measured fact.`;
  const revokedNote = row.revokedAt ? `\n**Revoked:** reality contradicted this rule after it had earned trust. Do not re-derive anything resembling it without strong new evidence.` : "";
  return `${header}\n**Rule:** ${row.content}\n**Source:** ${source}\n**Evidence:** ${evidenceFact} ${evidenceInterp}${revokedNote}`;
}

/** Full export: query all lessons, render, write-if-changed, commit. */
export async function exportLessonsMarkdown(): Promise<boolean> {
  const l = lessons();
  if (!l) return false;
  try {
    const rows = await l.findMany({ orderBy: [{ active: "desc" }, { score: "desc" }] });
    const total = rows.length;
    const activeCount = rows.filter((r: { active: boolean }) => r.active).length;
    const revokedCount = rows.filter((r: { revokedAt: Date | null }) => r.revokedAt).length;

    const body = rows.map((r: Parameters<typeof renderEntry>[0]) => renderEntry(r)).join("\n\n");
    const content =
      `# Lessons — the rules this system distilled from its own history\n\n` +
      `> Auto-generated by the distiller after every pass. Human-editable: the distiller\n` +
      `> sees your edits and won't re-derive a contradicting rule. One entry per lesson.\n` +
      `> ${activeCount} active · ${total - activeCount} inactive (${revokedCount} revoked) · generated ${new Date().toISOString().slice(0, 10)}\n\n` +
      `${body || "(no lessons yet — the distiller has not run)"}\n`;

    // Write only on change — no churn, no empty commits.
    let changed = true;
    try {
      if (existsSync(LESSONS_MD_PATH)) {
        const prev = readFileSync(LESSONS_MD_PATH, "utf-8");
        if (prev === content) changed = false;
      }
    } catch {
      /* treat as changed */
    }
    if (!changed) return false;

    mkdirSync(`${PROJECT_ROOT}/memory`, { recursive: true });
    writeFileSync(LESSONS_MD_PATH, content, "utf-8");
    commitLessonsFile();
    return true;
  } catch {
    return false;
  }
}

/** Best-effort git add+commit. No push — the loop's next pushCurrentState
 *  carries the file (it commits the live state). Contention with the
 *  loop's own git operations is expected occasionally; a failed commit
 *  here is caught and swallowed — the next export retries.
 *
 *  AUDIT 3 (F12): the commit is PATHSPEC-SCOPED (`git commit --
 *  memory/lessons.md`). The old pathless `git commit -m …` committed
 *  EVERYTHING staged — if the loop's own commit died mid-crash with
 *  files staged, the next lessons export folded the whole staged mutation
 *  into a commit labeled "memory: lessons.md export", misattributing the
 *  loop's changes to the distiller. With the pathspec, only lessons.md is
 *  committed (from the working tree we just wrote) and any unrelated
 *  staged files stay staged for their rightful owner. */
function commitLessonsFile(): void {
  try {
    const add = spawnSync("git", ["add", "memory/lessons.md"], { cwd: PROJECT_ROOT, timeout: 15000, stdio: "pipe" });
    if (add.status !== 0) return;
    // Empty-staged check: git diff --cached --quiet exits 0 when nothing
    // is staged (the file may have ridden along in a loop commit already).
    const quiet = spawnSync("git", ["diff", "--cached", "--quiet"], { cwd: PROJECT_ROOT, timeout: 15000, stdio: "pipe" });
    if (quiet.status === 0) return;
    spawnSync(
      "git",
      [
        "commit",
        "-m", "memory: lessons.md export (post-distillation mirror of the Lesson table)",
        "--no-verify",
        // AUDIT 3 (F12): pathspec — commit ONLY lessons.md, never whatever
        // else happens to be staged.
        "--", "memory/lessons.md",
      ],
      { cwd: PROJECT_ROOT, timeout: 30000, stdio: "pipe" }
    );
  } catch {
    /* best-effort */
  }
}

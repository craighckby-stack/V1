    doc.multiBuild(story)
    print("body built:", OUT_BODY)

    # merge cover (already rendered by html2poster.js)
    from pypdf import PdfReader, PdfWriter
    A4_W, A4_H = 595.28, 841.89

    def normalize(page):
        w, h = float(page.mediabox.width), float(page.mediabox.height)
        if abs(w - A4_W) > 0.1 or abs(h - A4_H) > 0.1:
            page.scale_to(A4_W, A4_H)
        return page

    writer = PdfWriter()
    cover = PdfReader(os.path.join(BG, "cover.pdf")).pages[0]
    writer.add_page(normalize(cover))
    for p in PdfReader(OUT_BODY).pages:
        writer.add_page(normalize(p))
    writer.add_metadata({"/Title": DOC_TITLE, "/Author": "Z.ai", "/Creator": "Z.ai",
                         "/Subject": "Complete build record and reproduction guide for the LOOP self-improvement system"})
    with open(OUT_FINAL, "wb") as f:
        writer.write(f)
    n = len(PdfReader(OUT_FINAL).pages)
    print(f"final: {OUT_FINAL}  ({n} pages, {os.path.getsize(OUT_FINAL):,} bytes)")



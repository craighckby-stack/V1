def embed_image(path, max_w=AVAIL_W, max_h=300):
    w, h = ImageReader(path).getSize()
    ratio = min(max_w / w if w > max_w else 1.0, max_h / h if h > max_h else 1.0)
    return Image(path, width=w * ratio, height=h * ratio)


def stat_strip(items):
    row, widths = [], []
    n = len(items)
    gap = 10
    cell_w = (AVAIL_W - gap * (n - 1)) / n
    for i, (big, label) in enumerate(items):
        big_fmt = big.format_map(STATS) if "{" in big else big
        row.append([Paragraph(f"<b>{big_fmt}</b>", S["stat"]),
                    Paragraph(label.format_map(STATS) if "{" in label else label, S["statlabel"])])
        widths.append(cell_w)
        if i < n - 1:
            row.append("")
            widths.append(gap)
    t = Table([row], colWidths=widths, hAlign="CENTER")
    cmds = [("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4)]
    for i in range(0, 2 * n - 1, 2):
        cmds.append(("BACKGROUND", (i, 0), (i, 0), CARD_BG))
        cmds.append(("BOX", (i, 0), (i, 0), 1, ACCENT))
    t.setStyle(TableStyle(cmds))
    return [Spacer(1, 6), t, Spacer(1, 14)]


def make_table(spec):
    cols = spec["cols"]
    ratios = spec.get("ratios") or [1.0 / len(cols)] * len(cols)
    total = sum(ratios)
    col_w = [r / total * AVAIL_W * 0.98 for r in ratios]
    assert sum(col_w) <= AVAIL_W + 0.5
    data = [[Paragraph(f"<b>{c}</b>", S["th"]) for c in cols]]
    for row in spec["rows"]:
        data.append([Paragraph(cell.format_map(STATS) if isinstance(cell, str) and "{" in cell else cell, S["td"])
                     for cell in row])
    t = Table(data, colWidths=col_w, hAlign="CENTER", repeatRows=1)
    cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            cmds.append(("BACKGROUND", (0, i), (-1, i), TABLE_STRIPE))
    t.setStyle(TableStyle(cmds))
    out = [Spacer(1, 12), t]
    if spec.get("caption"):
        out += [Spacer(1, 6), Paragraph(spec["caption"].format_map(STATS), S["caption"]), Spacer(1, 14)]
    else:
        out += [Spacer(1, 14)]
    return out


def resolve_figure(path):
    for cand in (os.path.join(BG, "charts", path), os.path.join(BG, path), os.path.join(ROOT, path), path):
        if os.path.exists(cand):
            return cand
    raise FileNotFoundError(path)


FIG_MAX_H = 300


def figure_block(path, caption, max_h=FIG_MAX_H):
    img = embed_image(resolve_figure(path), max_h=max_h)
    cap = Paragraph(caption.format_map(STATS), S["caption"])
    return [Spacer(1, 18), KeepTogether([img, Spacer(1, 8), cap]), Spacer(1, 18)]


def render_blocks(story, blocks, body_start_first=False):
    first_h1 = True
    for blk in blocks:
        kind = blk[0]
        if kind == "h1":
            story.extend(heading1(blk[1], body_start=body_start_first and first_h1))
            first_h1 = False
        elif kind == "h2":
            story.extend(heading2(blk[1]))
        elif kind == "h3":
            story.extend(heading3(blk[1]))
        elif kind == "p":
            story.append(Paragraph(blk[1].format_map(STATS), S["body"]))
        elif kind == "bullet":
            for item in blk[1]:
                story.append(Paragraph(item.format_map(STATS), S["bullet"], bulletText="\u2022"))
            story.append(Spacer(1, 6))
        elif kind == "numbered":
            for i, item in enumerate(blk[1], 1):
                story.append(Paragraph(item.format_map(STATS), S["bullet"], bulletText=f"{i}."))
            story.append(Spacer(1, 6))
        elif kind == "callouts":
            story.extend(stat_strip(blk[1]))
        elif kind == "quote":
            story.append(Paragraph(blk[1].format_map(STATS), S["quote"]))
        elif kind == "figure":
            story.extend(figure_block(blk[1], blk[2], max_h=blk[3] if len(blk) > 3 else FIG_MAX_H))
        elif kind == "table":
            story.extend(make_table(blk[1]))
        elif kind == "spacer":
            story.append(Spacer(1, blk[1]))


# ── appendix A: core source verbatim ────────────────────────────
def core_file_order():
    order = ["prisma/schema.prisma", "src/lib/db.ts", "src/lib/utils.ts"]
    files = {f["path"]: f for f in D["files"] if f["bucket"] == "core"}
    def key(p):
        if p.startswith("src/lib/pipeline/"):
            return "3|" + p
        if p.startswith("src/app/api/"):
            return "4|" + p
        if p.startswith("src/app/display/"):
            return "5|" + p
        if p == "src/app/page.tsx":
            return "6|" + p
        if p.startswith("mini-services/"):
            return "7|" + p
        return "9|" + p
    rest = sorted([p for p in files if p not in order], key=key)
    return [p for p in order if p in files] + rest


def appendix_a(story):
    story.extend(heading1("Appendix A — LOOP Core, Verbatim"))
    story.append(Paragraph(
        "The complete source of the system, exactly as tracked at the derivation commit — "
        f"{STATS['core_files']} files, {STATS['core_lines']:,} lines. Two transcription rules apply, "
        "both mechanical and disclosed here: lines longer than 86 characters are hard-wrapped with a "
        "two-space-plus-greater-than continuation prefix, and glyph characters absent from the PDF "
        "monospace font are substituted with bracketed ASCII tags (for example [OK], [LOCK], [TARGET]). "
        "No other alteration. The authoritative bytes remain the git objects; this appendix exists so "
        "the printed record is complete without a terminal.", S["body"]))
    story.append(Spacer(1, 6))
    files = {f["path"]: f for f in D["files"] if f["bucket"] == "core"}
    for path in core_file_order():
        f = files[path]
        if f["binary"] or f["path"].endswith(".gitkeep"):
            story.append(Paragraph(f"{path} — binary or empty placeholder, {f['bytes']} bytes", S["codehdr"]))
            continue
        raw = open(os.path.join(ROOT, path), encoding="utf-8", errors="replace").read()
        story.append(Paragraph(f"{path}  —  {f['lines']} lines", S["codehdr"]))
        story.append(code_preformatted(raw))
    return story



# ── verbatim sanitizer (font coverage) ──────────────────────────
EMOJI_MAP = {
    0x2705: "[OK]", 0x274C: "[FAIL]", 0x1F3AF: "[TARGET]", 0x1F512: "[LOCK]",
    0x26A0: "[WARN]", 0x23F3: "[WAIT]", 0x2B50: "[STAR]", 0x1F6A8: "[ALERT]",
    0x2757: "[!]", 0x1F534: "[RED]", 0x1F7E2: "[GREEN]", 0x26AB: "[DOT]",
}
MONO_GLYPHS = pdfmetrics.getFont("DejaVuSans").face.charToGlyph


def sanitize_verbatim(text):
    out = []
    for ch in text:
        o = ord(ch)
        if o in EMOJI_MAP:
            out.append(EMOJI_MAP[o])
        elif o in (0xFE0F, 0x200D, 0x200B, 0xFEFF):
            continue
        elif o < 32 and ch not in "\n\t":
            continue
        elif o > 126 and o not in MONO_GLYPHS:
            out.append(f"[U+{o:04X}]")
        else:
            out.append(ch)
    s = "".join(out)
    return s.replace("\t", "  ").replace("\ufeff", "")


CODE_WRAP = 86
CONT = "  > "


def wrap_code_line(line):
    if len(line) <= CODE_WRAP:
        return [line]
    parts = []
    while len(line) > CODE_WRAP:
        parts.append(line[:CODE_WRAP])
        line = CONT + line[CODE_WRAP - len(CONT) + 2:]
    if line:
        parts.append(line)
    return parts


def code_preformatted(raw_text):
    lines = []
    for ln in sanitize_verbatim(raw_text).split("\n"):
        lines.extend(wrap_code_line(ln.rstrip()))
    return Preformatted("\n".join(lines), S["code"])


# ── TOC doc template ────────────────────────────────────────────
class TocDocTemplate(SimpleDocTemplate):
    def beforeDocument(self):
        # reset per multiBuild pass — a stale value from an earlier pass
        # (when the TOC was shorter) would misnumber the front matter.
        self._body_start_page = None

    def handle_pageEnd(self):
        # draw footer at page END: by now the body-start marker flowable
        # has drawn if this page begins the body, so roman/arabic resolve
        # correctly for the page being closed.
        on_page(self.canv, self)
        SimpleDocTemplate.handle_pageEnd(self)

    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            if getattr(flowable, "body_start", False):
                self._body_start_page = self.page
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            bs = getattr(self, "_body_start_page", None)
            # TOC prints the displayed folio (arabic, reset at Chapter 1),
            # not the internal page index — matches the footer numbering.
            display = self.page - bs + 1 if bs else self.page
            self.notify("TOCEntry", (level, text, display, key))



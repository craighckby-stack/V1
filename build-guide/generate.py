    plat = sorted((x for x in D["files"] if x["bucket"] == "platform"), key=lambda x: x["path"])
    groups = {}
    for f in plat:
        g = f["path"].split("/")[1] if f["path"].count("/") >= 1 else "(root)"
        groups.setdefault(g, []).append(f)
    cols = ["File", "Lines"]
    ratios = [0.86, 0.14]
    col_w = [r / sum(ratios) * AVAIL_W * 0.98 for r in ratios]
    data = [[Paragraph(f"<b>{c}</b>", S["th"]) for c in cols]]
    cmds = [("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]
    ridx = 1
    stripe_toggle = False
    for g in sorted(groups):
        members = groups[g]
        glines = sum(f["lines"] or 0 for f in members)
        data.append([Paragraph(f"<b>skills/{g}</b> — {len(members)} files, {glines:,} lines", S["th"]), Paragraph("", S["td"])])
        cmds.append(("BACKGROUND", (0, ridx), (-1, ridx), COVER_BLOCK))
        cmds.append(("SPAN", (0, ridx), (-1, ridx)))
        ridx += 1
        for f in sorted(members, key=lambda x: x["path"]):
            rel = f["path"][len("skills/"):]
            data.append([Paragraph(rel, S["td"]), Paragraph(str(f["lines"] or 0), S["td"])])
            if stripe_toggle:
                cmds.append(("BACKGROUND", (0, ridx), (-1, ridx), TABLE_STRIPE))
            stripe_toggle = not stripe_toggle
            ridx += 1
    t = Table(data, colWidths=col_w, hAlign="CENTER", repeatRows=1)
    t.setStyle(TableStyle(cmds))
    story.extend([Spacer(1, 12), t, Spacer(1, 6),
                  Paragraph(f"Table C1 — Platform skills inventory: {STATS['platform_files']:,} files in {len(groups)} skills.", S["caption"]),
                  Spacer(1, 14)])
    return story


